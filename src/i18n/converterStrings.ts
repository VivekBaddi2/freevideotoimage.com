export function getConverterStrings(lang?: SupportedLanguage): ConverterDictionary {
  if (lang && lang in converterStrings) {
    return converterStrings[lang];
  }
  // Try detecting from window.location if running on client-side
  if (typeof window !== 'undefined' && window.location?.pathname) {
    const segments = window.location.pathname.split('/').filter(Boolean);
    const pathLang = segments[0];
    if (pathLang && pathLang in languages) {
      return converterStrings[pathLang as SupportedLanguage];
    }
  }
  return converterStrings[defaultLang];
}

